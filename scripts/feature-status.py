#!/usr/bin/env python3
"""Writes the implementation status into README.md from the feature map.

    python3 -I scripts/feature-status.py           # rewrite the section in README.md
    python3 -I scripts/feature-status.py --check   # exit 1 if README.md is out of date (CI)

Source: the frontmatter (`priority`, `arztagent`, `status`) and the `Sub-features` lines
(`built`, `partial`, `missing`) of .agents/skills/verify-schlange/features/*.md. The section
sits between the markers <!-- feature-status:start --> and <!-- feature-status:end -->.
"""

import re
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FEATURES = ROOT / ".agents/skills/verify-schlange/features"
README = ROOT / "README.md"
START, END = "<!-- feature-status:start -->", "<!-- feature-status:end -->"
SUB = re.compile(r"^- `[^`]+`:\s*(built|partial|missing|not built)", re.M | re.I)
PRIORITY = {"P1": "P1 – what Arztagent uses", "P2": "P2 – the rest of Mergify's merge queue and rules",
            "P3": "P3 – other Mergify products"}


def features():
    out = []
    for f in sorted(FEATURES.glob("*.md")):
        text = f.read_text()
        m = re.match(r"---\n(.*?)\n---", text, re.S)
        if not m:
            continue
        fm = dict(re.findall(r"^(\w+):\s*(.*)$", m.group(1), re.M))
        section = text.split("## Sub-features", 1)[-1].split("\n## ", 1)[0]
        subs = Counter("missing" if s.lower() == "not built" else s.lower() for s in SUB.findall(section))
        out.append({
            "id": fm.get("id", f.stem), "title": fm.get("title", "").strip('"'), "file": f.name,
            "priority": fm.get("priority", "?"), "status": fm.get("status", "?"),
            "arztagent": fm.get("arztagent") == "true", "subs": subs,
        })
    return out


def render(fs):
    status = Counter(f["status"] for f in fs)
    subs = sum((f["subs"] for f in fs), Counter())
    az = sum((f["subs"] for f in fs if f["arztagent"]), Counter())
    lines = [
        START,
        "<!-- generated by scripts/feature-status.py from the feature map; do not edit by hand -->",
        "",
        "Every Mergify feature has a file in the feature map "
        "([`.agents/skills/verify-schlange/features/`](.agents/skills/verify-schlange/features/)). "
        "A feature is **conformant** only after a green verification and an independent critic "
        "verdict; **partial** means some of its sub-features are built; **missing** means none.",
        "",
        "| | conformant | partial | missing |",
        "|---|---:|---:|---:|",
        f"| Features ({len(fs)}) | {status['conformant']} | {status['partial']} | {status['missing']} |",
        f"| Sub-features ({sum(subs.values())}) | – | built {subs['built']}, partial {subs['partial']} | {subs['missing']} |",
        f"| Sub-features Arztagent uses ({sum(az.values())}) | – | built {az['built']}, partial {az['partial']} | {az['missing']} |",
        "",
    ]
    for prio, label in PRIORITY.items():
        group = [f for f in fs if f["priority"] == prio]
        if not group:
            continue
        c = Counter(f["status"] for f in group)
        lines += [
            "<details>",
            f"<summary><b>{label}</b>: {len(group)} features ({c['conformant']} conformant, "
            f"{c['partial']} partial, {c['missing']} missing)</summary>",
            "",
            "| Feature | Status | Sub-features built / partial / missing | Arztagent |",
            "|---|---|---|---|",
        ]
        for f in sorted(group, key=lambda x: (x["status"] != "conformant", x["status"] != "partial", x["id"])):
            s = f["subs"]
            lines.append(
                f"| [{f['title'] or f['id']}](.agents/skills/verify-schlange/features/{f['file']}) | {f['status']} "
                f"| {s['built']} / {s['partial']} / {s['missing']} | {'yes' if f['arztagent'] else ''} |")
        lines += ["", "</details>", ""]
    lines.append(END)
    return "\n".join(lines)


def main():
    readme = README.read_text()
    if START not in readme or END not in readme:
        sys.exit(f"{README} has no {START} … {END} section")
    head, rest = readme.split(START, 1)
    tail = rest.split(END, 1)[1]
    new = head + render(features()) + tail
    if "--check" in sys.argv:
        if new != readme:
            print("README.md feature status is out of date: python3 -I scripts/feature-status.py", file=sys.stderr)
            sys.exit(1)
        return
    README.write_text(new)


if __name__ == "__main__":
    main()
